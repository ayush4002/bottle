      card.classList.remove('open');
    } else {
      card.classList.add('open');
    }
    const btnText = card.querySelector('.about-btn-text');
    if (btnText) {
      btnText.textContent = card.classList.contains('open') ? 'Read Less' : 'Read More';
    }
  };
